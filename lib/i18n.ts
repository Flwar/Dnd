const hebrewNumber = new Intl.NumberFormat("he-IL");

export const heFormat = {
  number(value: number) {
    return hebrewNumber.format(value);
  },
  percent(value: number) {
    return `${hebrewNumber.format(value)}%`;
  },
  fraction(current: number, maximum: number) {
    return `${hebrewNumber.format(current)} / ${hebrewNumber.format(maximum)}`;
  },
  resource(label: string, current: number, maximum: number) {
    return `${label}: ${hebrewNumber.format(current)} מתוך ${hebrewNumber.format(maximum)}`;
  },
};
